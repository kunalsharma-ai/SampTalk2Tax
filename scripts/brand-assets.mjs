#!/usr/bin/env node
/**
 * Builds every Talk2Tax logo file the apps use from the brand source in
 * packages/design-system/brand (icon.svg, logo-dark.svg, logo-light.svg). Run it after the
 * brand files change, then commit what it writes:
 *
 *   node scripts/brand-assets.mjs
 *
 * It needs Playwright's Chromium (a devDependency of apps/web) to turn SVG into PNG.
 *
 * Writes:
 *   apps/web/public/brand/*.svg      animated and still logos for the web app
 *   apps/web/public/brand/icon-*.png app icons for the web manifest
 *   apps/web/src/app/icon.svg        favicon (still, cropped to the mark)
 *   apps/web/src/app/apple-icon.png  home-screen icon (opaque, 180 px)
 *   apps/api/src/common/brand-assets.ts  PNGs for emails and PDFs, as base64
 */
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = (f) => readFileSync(join(root, 'packages/design-system/brand', f), 'utf8');
const out = (f, data) => {
  const p = join(root, f);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
  console.log('wrote', f);
};

/** The same file with every animation off: what reduced-motion users see, and what print, favicons and email need. */
const still = (svg) => svg.replace('</style>', '*{animation:none!important}</style>');
/** The icon cropped to the speech bubbles, so it fills small favicon squares. */
const cropped = (svg) => svg.replace('viewBox="-7 -7 78 78"', 'viewBox="1 3 62 62"');

const icon = src('icon.svg');
const dark = src('logo-dark.svg');
const light = src('logo-light.svg');

out('apps/web/public/brand/logo-dark.svg', dark);
out('apps/web/public/brand/logo-light.svg', light);
out('apps/web/public/brand/logo-dark-still.svg', still(dark));
out('apps/web/public/brand/logo-light-still.svg', still(light));
out('apps/web/public/brand/icon.svg', icon);
out('apps/web/public/brand/icon-still.svg', still(icon));
out('apps/web/src/app/icon.svg', cropped(still(icon)));

const { chromium } = createRequire(join(root, 'apps/web/package.json'))('playwright');
const browser = await chromium.launch();
const page = await browser.newPage();

/** Renders an SVG to a PNG of the given CSS size, on a transparent or solid background. */
async function png(svg, width, height, { background = 'transparent', inset = 0 } = {}) {
  await page.setViewportSize({ width, height });
  const uri = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  await page.setContent(
    `<html><body style="margin:0;background:${background}"><img src="${uri}" style="display:block;box-sizing:border-box;width:${width}px;height:${height}px;padding:${inset}px"></body></html>`,
  );
  await page.waitForFunction(() => document.images[0].complete);
  return page.screenshot({ omitBackground: background === 'transparent', type: 'png' });
}

const NAVY = '#050a18';
out('apps/web/src/app/apple-icon.png', await png(cropped(still(icon)), 180, 180, { background: NAVY, inset: 24 }));
out('apps/web/public/brand/icon-192.png', await png(still(icon), 192, 192));
out('apps/web/public/brand/icon-512.png', await png(still(icon), 512, 512));
// Maskable icons keep the mark inside the middle 80% safe zone.
out('apps/web/public/brand/icon-maskable-512.png', await png(cropped(still(icon)), 512, 512, { background: NAVY, inset: 96 }));

// Emails and PDFs: drawn at twice their display size so they stay sharp.
await page.close();
const hi = await browser.newPage({ deviceScaleFactor: 2 });
async function png2x(svg, width, height) {
  await hi.setViewportSize({ width, height });
  const uri = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  await hi.setContent(`<html><body style="margin:0;background:transparent"><img src="${uri}" style="display:block;width:${width}px;height:${height}px"></body></html>`);
  await hi.waitForFunction(() => document.images[0].complete);
  return hi.screenshot({ omitBackground: true, type: 'png' });
}
const emailLogo = await png2x(still(light), 234, 64);
const pdfIcon = await png2x(cropped(still(icon)), 24, 24);
await browser.close();

out(
  'apps/api/src/common/brand-assets.ts',
  `/**
 * Talk2Tax logo images for emails and PDFs. Generated by scripts/brand-assets.mjs from
 * packages/design-system/brand; do not edit by hand.
 */

/** The light wordmark ("Talk2Tax · Talk. File. Relax. · by Sampledge"), 468 × 128 px, shown at 234 × 64. */
export const EMAIL_LOGO_PNG = Buffer.from(
  '${emailLogo.toString('base64')}',
  'base64',
);
export const EMAIL_LOGO_SIZE = { width: 234, height: 64 } as const;

/** The mark alone (two speech bubbles with a percent sign), 48 × 48 px, for PDF footers. */
export const PDF_ICON_PNG = Buffer.from(
  '${pdfIcon.toString('base64')}',
  'base64',
);
`,
);
